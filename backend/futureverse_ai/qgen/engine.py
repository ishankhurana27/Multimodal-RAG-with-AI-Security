BASE_FORMAT_SYSTEM = """You are an author of UPSC Civil Services examination questions.

A control block fixes the topic and the question format. When an <evidence> block is present every factual premise you write must be traceable to it; when it is absent, use your own knowledge of the subject and stay inside the named topic.

Emit exactly one JSON object and nothing else — no prose, no code fence.

Rules:
- Never write an option letter (a/b/c/d) and never write an answer code. The answer key and the option order are produced by the application from the truth values you supply.
- Every element must be a real entity used precisely — a neighbouring Article, the right power attributed to the wrong body, an adjacent amendment number. Never an absurd option no candidate would pick.
- Never refer to the source document, a passage, a figure or a page number. Test subject knowledge only.
- Difficulty must come from close distinctions, not from obscure trivia or trick wording.
- Do not write an explanation field. The application writes the explanation separately."""

AR_SCHEMA_PROMPT = """{"format":"assertion_reason","assertion":"<a single factual claim>","reason":"<a single factual claim offered as the cause or basis of A>","assertion_true":<bool>,"reason_true":<bool>,"reason_explains":<bool>}

Write the pair so that the intended case below holds, and set the three booleans to match exactly:
{case_instruction}

Craft rules:
- A and R must each be ONE self-contained sentence about the named topic, no lists.
- R must be genuinely relevant to A — a plausible-sounding cause a candidate might accept — never an unrelated fact.
- `reason_explains` is true ONLY when R is the actual constitutional/legal/causal reason A holds; two true statements that merely sit next to each other are the "not the correct explanation" case.
- Never state the answer, never mention options."""

AR_CASES = {
    "a": ("Both A and R are true, and R IS the correct explanation of A. "
          "Set assertion_true=true, reason_true=true, reason_explains=true."),
    "b": ("Both A and R are true, but R is NOT the correct explanation of A — "
          "R must be a true fact that a candidate would wrongly accept as the cause. "
          "Set assertion_true=true, reason_true=true, reason_explains=false."),
    "c": ("A is true but R is false — R must be a plausible-sounding but factually "
          "wrong claim. Set assertion_true=true, reason_true=false, reason_explains=false."),
    "d": ("A is false but R is true — A must be a common misconception, R a correct "
          "fact. Set assertion_true=false, reason_true=true, reason_explains=false."),
}

MATCH_SCHEMA_PROMPT = """{"format":"match_the_following","stem":"Match List-I (<what the left column holds>) with List-II (<what the right column holds>):","pairs":[{"left":"<item>","right":"<its correct match>"}, ...]}

Give exactly {n_pairs} pairs, each correct.

Craft rules:
- All List-I entries must be the SAME kind of thing (all Articles, or all committees, or all schedules) and all List-II entries the same kind as each other.
- Every List-II entry must be a plausible match for every List-I entry at first glance — that is what makes the question testable. If one pairing is obvious from wording alone, replace it.
- Do not number or letter the items, and do not shuffle them: supply correct pairs only. The application shuffles List-II and builds the answer code.
- No item may appear twice in either list."""


def base_format_user_msg(control: str, ev_block: str, fmt: str,
                         ar_case: str = "a", n_pairs: int = 4) -> str:
    # NB: these templates contain literal JSON braces, so they are filled by
    # substring replacement — str.format() would try to read {"format": ...}
    # as a field name.
    if fmt == "assertion_reason":
        schema = AR_SCHEMA_PROMPT.replace("{case_instruction}",
                                          AR_CASES.get(ar_case, AR_CASES["a"]))
    elif fmt == "match_the_following":
        schema = MATCH_SCHEMA_PROMPT.replace("{n_pairs}", str(n_pairs))
    else:
        raise ValueError(f"no base-model prompt for format {fmt!r}")
    return "\n".join(filter(None, [control, ev_block, "<schema>", schema, "</schema>"]))

# ── token helpers (06_build_sft.py's _toks, minus the IDF grounder) ──────────
_TOK = re.compile(r"[a-z0-9]{3,}")
_STOP = frozenset(
    "the and for with that this from are was were has have had not which "
    "following statements statement consider given above correct incorrect "
    "respect reference regarding india indian".split()
)


def _toks(text: str) -> set[str]:
    return {w for w in _TOK.findall((text or "").lower()) if w not in _STOP}


def truncate(text: str, limit: int) -> str:
    """Trim to `limit` chars, preferring a sentence boundary (06's truncate)."""
    if len(text) <= limit:
        return text
    cut = text[:limit]
    for sep in (". ", "; ", "\n"):
        i = cut.rfind(sep)
        if i > limit * 0.6:
            return cut[: i + 1].rstrip()
    return cut.rstrip() + " …"


def best_window(text: str, qt: set[str], limit: int, stride: int = 300) -> str:
    """The slice of the chunk densest in the query tokens.

    Serving twin of 06's best_window. Training scored windows with the IDF
    grounder against the *target question*; at serving there is no target
    question yet, so windows are scored by plain overlap with the topic
    tokens — same snapping to sentence boundaries, same shape of output.
    """
    text = (text or "").strip()
    if len(text) <= limit:
        return truncate(text, limit)
    best, best_score = text[:limit], -1.0
    for start in range(0, max(1, len(text) - limit + 1), stride):
        w = text[start : start + limit]
        sc = float(len(_toks(w) & qt))
        if sc > best_score:
            best, best_score = w, sc
    i = best.find(". ")
    if 0 < i < limit * 0.25:
        best = best[i + 2 :]
    j = best.rfind(". ")
    if j > len(best) * 0.6:
        best = best[: j + 1]
    return best.strip()


# ── prompt builders (byte-compatible with 06_build_sft.py) ───────────────────

def control_block(
    *,
    task: str,
    subject: str,
    topic: str,
    fmt: str,
    subtopic: str = "",
    n_statements: Optional[int] = None,
    cognitive: str = "any",
    grounding: str = "evidence",
) -> str:
    lines = [
        f"<task>{task}</task>",
        "<control>",
        f"subject: {subject or 'Indian Polity'}",
        f"topic: {topic or '—'}",
    ]
    if subtopic:
        lines.append(f"subtopic: {subtopic}")
    lines.append(f"format: {fmt}")
    if fmt == "multi_statement" and n_statements:
        lines.append(f"statements: {n_statements}")
    lines += [f"cognitive: {cognitive}", f"grounding: {grounding}", "</control>"]
    return "\n".join(lines)


def evidence_block(text: str, ref: str, query_tokens: set[str], max_chars: int = 2400) -> str:
    """Training always used id="S1" for the (single) evidence chunk.

    06 wrote breadcrumbs into ref verbatim (including their " > " separators),
    so the only character removed here is the double quote, which would break
    the attribute quoting.
    """
    ref = (ref or "").replace('"', "").strip()
    ref_attr = f' ref="{ref}"' if ref else ""
    body = best_window(text, query_tokens, max_chars)
    return f'<evidence id="S1"{ref_attr}>\n{body}\n</evidence>'


def generate_user_msg(control: str, ev_block: str) -> str:
    return "\n".join(filter(None, [control, ev_block]))


def repair_user_msg(control: str, ev_block: str, draft: dict, rule: int, reason: str) -> str:
    """task=repair message, laid out exactly as 06's make_row() built it."""
    return "\n".join(
        filter(
            None,
            [
                control,
                ev_block,
                "<draft>",
                json.dumps(draft, ensure_ascii=False),
                "</draft>",
                "<review>",
                json.dumps({"rule_violated": rule, "reason": reason}, ensure_ascii=False),
                "</review>",
            ],
        )
    )


# ── deterministic checks (regex families shared with training/eval) ──────────

# 06_build_sft.py ANSWER_CODE_RE — a statement/choice that IS an answer code.
ANSWER_CODE_RE = re.compile(
    r"""^\s*(?:
   (?:both\s+)?statement[\s\-]?(?:i|ii|1|2)\b
 | (?:only\s+)?\d(?:\s*(?:,|and)\s*\d)*\s+only\b
 | both\s+\d\s+and\s+\d
 | all\s+(?:of\s+)?the\s+(?:above|three|four|statements)
 | neither\s+\d\s+nor\s+\d
 | (?:both\s+)?a\s+and\s+r\b
 | a\s+is\s+(?:true|correct)
 | none\s+of\s+the\s+above
 | \d\s*,\s*\d\s+and\s+\d
)""",
    re.I | re.X,
)
# evaluate.py's stem-level leak / meta-reference detectors.
LETTER_RE = re.compile(r"\b(?:option|answer)\s*\(?[a-d]\)?\b", re.I)
META_RE = re.compile(
    r"\b(?:passage|paragraph|figure|the above text|given text|source material|"
    r"document|extract|as mentioned above)\b",
    re.I,
)
NEG_STEM_RE = re.compile(r"\b(?:not|except|incorrect)\b", re.I)


def question_text_of(obj: dict) -> str:
    return " ".join(
        [obj.get("stem") or ""]
        + [s.get("text", "") for s in (obj.get("statements") or []) if isinstance(s, dict)]
        + [c.get("text", "") for c in (obj.get("choices") or []) if isinstance(c, dict)]
    ).strip()


def truth_pattern(obj: dict) -> Optional[str]:
    """'mixed' | 'all_true' | 'all_false' for multi_statement; None otherwise."""
    st = obj.get("statements")
    if not isinstance(st, list) or not st:
        return None
    truths = [s.get("truth") for s in st if isinstance(s, dict)]
    if len(truths) != len(st) or not all(isinstance(t, bool) for t in truths):
        return None
    if all(truths):
        return "all_true"
    if not any(truths):
        return "all_false"
    return "mixed"


def statement_dup_jaccard(obj: dict) -> float:
    """Max pairwise word-jaccard among statement/choice texts (near-dup guard)."""
    items = [s.get("text", "") for s in (obj.get("statements") or []) if isinstance(s, dict)]
    items += [c.get("text", "") for c in (obj.get("choices") or []) if isinstance(c, dict)]
    sets = [set(re.findall(r"[a-z0-9]+", t.lower())) for t in items if t]
    worst = 0.0
    for i in range(len(sets)):
        for j in range(i + 1, len(sets)):
            if not sets[i] or not sets[j]:
                continue
            jac = len(sets[i] & sets[j]) / len(sets[i] | sets[j])
            worst = max(worst, jac)
    return worst


# ── anti-regurgitation: never re-serve a training question ───────────────────
# The four-arm eval measured copy-of-source at 0.13-0.16 jaccard and a scan of
# 29 live questions against all 9,175 SFT targets found no whole-question reuse
# (max 5-gram jaccard 0.18) — but ONE generated statement was near-verbatim from
# a training statement. Measurement is not a guarantee, so this checks every
# generated statement/choice against a fingerprint of the training corpus built
# by qgen/scripts/build_question_fingerprints.py. Missing file = check disabled.

_FP_STATE: dict = {"stamp": None, "grams": frozenset()}


def _fingerprint_path() -> str:
    import os
    return os.environ.get(
        "QUESTION_FINGERPRINTS_PATH",
        os.path.join(os.environ.get("DATA_DIR", "data"), "question_fingerprints.json"))


def _fingerprints() -> frozenset:
    import os
    path = _fingerprint_path()
    try:
        stamp = (path, os.path.getmtime(path))
    except OSError:
        return frozenset()
    if _FP_STATE["stamp"] != stamp:
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
            _FP_STATE["grams"] = frozenset(data.get("grams") or [])
            _FP_STATE["stamp"] = stamp
            log.info("question fingerprints loaded: %d grams from %s",
                     len(_FP_STATE["grams"]), path)
        except Exception as e:
            log.warning("fingerprint load failed (check disabled): %s", e)
            return frozenset()
    return _FP_STATE["grams"]


def text_grams(text: str, n: int = 8) -> set:
    """Hashed word 8-grams — must match build_question_fingerprints.py exactly.

    n=8 chosen by sweep over the real corpus: it catches 100% of training text
    while flagging only the holdout sentences that genuinely are verbatim
    copies, whereas n=5 flagged ordinary standard phrasings too.
    """
    import zlib
    toks = [w for w in re.findall(r"[a-z0-9]+", (text or "").lower()) if len(w) > 2]
    return {zlib.crc32(" ".join(toks[i:i + n]).encode("utf-8"))
            for i in range(max(0, len(toks) - n + 1))}


def regurgitation_score(text: str) -> float:
    """Share of this text's 5-grams that occur somewhere in the training corpus."""
    fp = _fingerprints()
    if not fp:
        return 0.0
    g = text_grams(text)
    if not g:
        return 0.0
    return len(g & fp) / len(g)


def regurgitated_items(obj: dict, threshold: float = 0.75,
                       min_words: int = 12) -> list:
    """Individual statements/choices/A-R lines that echo a training question."""
    items = [s.get("text", "") for s in (obj.get("statements") or []) if isinstance(s, dict)]
    items += [c.get("text", "") for c in (obj.get("choices") or []) if isinstance(c, dict)]
    items += [obj.get("assertion") or "", obj.get("reason") or ""]
    items += [f"{p.get('left','')} {p.get('right','')}"
              for p in (obj.get("pairs") or []) if isinstance(p, dict)]
    out = []
    for t in items:
        t = (t or "").strip()
        if len(t.split()) >= min_words and regurgitation_score(t) >= threshold:
            out.append(t)
    return out


# ── difficulty: what makes a UPSC question easy ──────────────────────────────
# Measured on the 29-question audit batch: 19 carried at least one of these.
_VAGUE_STEM_RE = re.compile(
    r"most appropriate|best describes|which of the following is correct about", re.I)


def easiness_flags(obj: dict, rendered: dict = None) -> list:
    """Deterministic 'this question is easy' signals. Empty list = not easy."""
    flags = []
    fmt = obj.get("format")
    stem = obj.get("stem") or ""
    if fmt == "multi_statement":
        st = obj.get("statements") or []
        if len(st) == 2:
            # 2 statements => only 4 possible answer codes and the candidate can
            # often eliminate on one fact. Real papers use 3-4 far more often.
            flags.append("only 2 statements")
        truths = [s.get("truth") for s in st if isinstance(s, dict)]
        if truths and (all(truths) or not any(truths)):
            flags.append("answer is all/none of the statements")
    elif fmt == "select_identify":
        if len(stem) < 95 and not _VAGUE_STEM_RE.search(stem):
            flags.append("short single-fact recall stem")
        if _VAGUE_STEM_RE.search(stem):
            flags.append("vague 'most appropriate' stem")
    elif fmt == "assertion_reason":
        # the (a) case is the one candidates guess by default
        if obj.get("assertion_true") and obj.get("reason_true") and obj.get("reason_explains"):
            flags.append("A-R case (a): both true and R explains A")
    return flags


# ── option quality (select_identify) ─────────────────────────────────────────
def option_issues(obj: dict) -> list:
    """The tells that let a test-taker answer without knowing the subject."""
    issues = []
    ch = obj.get("choices") or []
    texts = [(c.get("text") or "").strip() for c in ch if isinstance(c, dict)]
    if len(texts) < 3:
        return issues
    lens = [len(t) for t in texts]
    correct = next((i for i, c in enumerate(ch)
                    if isinstance(c, dict) and c.get("correct")), None)
    ratio = max(lens) / max(1, min(lens))
    if correct is not None and lens[correct] == max(lens) and ratio > 1.6:
        # the classic giveaway: the fullest-looking option is the key
        issues.append(f"the correct option is the longest (ratio {ratio:.1f})")
    if ratio > 3.0:
        issues.append(f"option lengths are unbalanced (ratio {ratio:.1f})")
    words = [set(re.findall(r"[a-z0-9]+", t.lower())) for t in texts]
    for i in range(len(words)):
        for j in range(i + 1, len(words)):
            if words[i] and words[j]:
                jac = len(words[i] & words[j]) / len(words[i] | words[j])
                if jac > 0.8:
                    issues.append("two options are near-identical")
                    break
    return issues


def deterministic_issues(obj: dict, validate_fn, slot_format: str,
                         n_statements: Optional[int], dup_threshold: float = 0.6) -> list[str]:
    """Every check that needs no second model. Empty list = accept.

    Order matters only for readability; the caller resamples on ANY issue.
    """
    issues = list(validate_fn(obj))
    if issues:
        return issues
    if obj.get("format") != slot_format:
        issues.append(f"format drift: asked {slot_format}, got {obj.get('format')!r}")
    if slot_format == "match_the_following" and n_statements:
        got = len(obj.get("pairs") or [])
        if got != n_statements:
            issues.append(f"pair count drift: asked {n_statements}, got {got}")
    if slot_format == "multi_statement" and n_statements:
        got = len(obj.get("statements") or [])
        if got != n_statements:
            issues.append(f"statement count drift: asked {n_statements}, got {got}")
    items = [s.get("text", "") for s in (obj.get("statements") or []) if isinstance(s, dict)]
    items += [c.get("text", "") for c in (obj.get("choices") or []) if isinstance(c, dict)]
    if any(ANSWER_CODE_RE.match(t or "") for t in items) or LETTER_RE.search(question_text_of(obj)):
        issues.append("letter/answer-code leak")
    if META_RE.search(question_text_of(obj)):
        issues.append("meta reference to the source document")
    dup = statement_dup_jaccard(obj)
    if dup > dup_threshold:
        issues.append(f"near-duplicate statements (jaccard {dup:.2f})")
    issues += option_issues(obj)
    for t in regurgitated_items(obj):
        issues.append(f"echoes a training question: {t[:70]!r}")
    return issues


# ── JSON extraction ──────────────────────────────────────────────────────────

_THINK_RE = re.compile(r"<think>.*?</think>", re.S)


def first_json_object(text: str) -> Optional[dict]:
    """First balanced JSON object in a model reply.

    format="json" makes replies pure JSON in practice (600/600 in the eval),
    but the think-field fallback path can leave an inline <think> block, and
    older models fence their output — strip both before scanning.
    """
    if not text:
        return None
    text = _THINK_RE.sub("", text)
    text = re.sub(r"```(?:json)?", "", text).strip()
    start = text.find("{")
    if start == -1:
        return None
    depth, in_str, esc = 0, False, False
    for i in range(start, len(text)):
        ch = text[i]
        if in_str:
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == '"':
                in_str = False
            continue
        if ch == '"':
            in_str = True
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                try:
                    return json.loads(text[start : i + 1])
                except Exception:
                    try:
                        return json.loads(
                            re.sub(r",\s*([\]}])", r"\1", text[start : i + 1])
                        )
                    except Exception:
                        return None
    return None


# ── Ollama client (the exact request shape evaluate.py validated) ────────────

class OllamaError(RuntimeError):
    def __init__(self, status: int, detail: str):
        super().__init__(f"ollama {status}: {detail}")
        self.status = status
        self.detail = detail


async def ollama_chat(
    session: aiohttp.ClientSession,
    base_url: str,
    model: str,
    system: str,
    user: str,
    *,
    temperature: float = 0.6,
    num_predict: int = 1024,
    num_ctx: Optional[int] = None,
    think: Optional[bool] = False,
    json_format: bool = True,
    timeout: int = 300,
) -> str:
    """One /api/chat call; returns message.content.

    think=False is the eval-validated setting for the Qwen3-family SFT model.
    A 400 mentioning the think field gets one retry without it (evaluate.py's
    fallback for older Ollama builds); any inline <think> the fallback lets
    through is stripped by first_json_object().
    """
    options: dict = {"temperature": temperature, "num_predict": num_predict}
    if num_ctx:
        options["num_ctx"] = num_ctx
    req: dict = {
        "model": model,
        "stream": False,
        "options": options,
        "messages": [
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ],
    }
    if json_format:
        req["format"] = "json"
    if think is not None:
        req["think"] = think

    for attempt in (0, 1):
        try:
            async with session.post(
                f"{base_url.rstrip('/')}/api/chat",
                json=req,
                timeout=aiohttp.ClientTimeout(total=timeout),
            ) as resp:
                if resp.status == 400 and "think" in req and attempt == 0:
                    del req["think"]
                    continue
                if resp.status != 200:
                    detail = (await resp.text())[:400]
                    raise OllamaError(resp.status, detail)
                out = await resp.json()
                return ((out.get("message") or {}).get("content")) or ""
        except aiohttp.ClientError as e:
            raise OllamaError(0, f"connection to {base_url} failed: {e}") from e
    return ""


def is_model_missing(err: OllamaError) -> bool:
    return err.status == 404 or "not found" in (err.detail or "").lower()


