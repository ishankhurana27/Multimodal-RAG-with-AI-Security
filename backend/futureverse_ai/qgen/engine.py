"""
engine.py — serving primitives for the fine-tuned semantic question model.

Everything here exists to keep three surfaces byte-consistent:

  train   qgen/scripts/06_build_sft.py wrote the SFT rows
  eval    qgen/scripts/evaluate.py measured the four arms
  serve   this module + routers/questions.py

Contract anchors (do not "improve" these without retraining):

* SYSTEM_PROMPT is read from system_prompt.txt next to this file, which must
  stay byte-identical to qgen/data/sft/system_prompt.txt and to the SYSTEM
  string in the Ollama Modelfile. It is sent explicitly on every generation
  call — exactly what evaluate.py did — so serving does not depend on which
  Modelfile the target Ollama happens to have.
* control_block() / evidence_block() reproduce 06_build_sft.py's output format
  exactly, including the em-dash topic fallback and the fixed `id="S1"` (the
  training data always labelled its single evidence chunk S1, whatever the
  retrieval slot was called).
* ollama_chat() sends the exact request shape evaluate.py validated:
  format="json", options={temperature, num_predict}, think=False for the
  Qwen3-family SFT model, with the one-shot retry that drops the think field
  on a 400 from older Ollama builds.

Guardrails implemented here (verdict: reports/verdict_qwen3_sft.md):
  1 always-evidence   — the caller only ever generates with an evidence block
  2 truth-mix quota   — truth_pattern() feeds the router's resample loop
  3 verify pass       — judge_statements()/judge_choices(): an independent
                        model re-derives the truths; negative stems are handled
                        by having the judge answer the question itself
  4 near-dup check    — statement_dup_jaccard() feeds the resample loop

Dependencies: stdlib + aiohttp (already an open-webui core dependency).
"""
